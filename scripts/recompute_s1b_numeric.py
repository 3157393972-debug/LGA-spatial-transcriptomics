#!/usr/bin/env python3
"""Calculate Donor 1 group-count sensitivity from saved paired main-run latents.

Input: nine NPZ files, one for each adjacent pair and seed 42/123/456.
The donor-first depth coordinates and original embeddings are stored in each NPZ.
This script computes numbers only; it does not draw figures or train a model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

K_VALUES = (3, 5, 7, 10, 15)
LAYER_MAP = {f"Layer_{i}": f"L{i}" for i in range(1, 7)}


def depth_groups(depth: np.ndarray, k: int) -> np.ndarray:
    depth = np.asarray(depth, dtype=np.float64)
    scaled = (depth - depth.min()) / (depth.max() - depth.min() + 1e-8)
    return np.digitize(scaled, np.linspace(0, 1, k + 1)[1:-1])


def zca(h: np.ndarray) -> np.ndarray:
    centered = h - h.mean(axis=0, keepdims=True)
    cov = centered.T @ centered / (len(h) - 1)
    u, values, _ = np.linalg.svd(cov, full_matrices=False)
    return centered @ u @ np.diag(1.0 / np.sqrt(values + 1e-8)) @ u.T


def lga_auto(source: np.ndarray, target: np.ndarray, gs: np.ndarray, gt: np.ndarray):
    source_w, target_w = zca(source), zca(target)
    common = sorted(set(gs.tolist()) & set(gt.tolist()))
    cs = np.array([source_w[gs == group].mean(axis=0) for group in common])
    ct = np.array([target_w[gt == group].mean(axis=0) for group in common])
    u, _, vt = np.linalg.svd(cs.T @ ct)
    return source_w @ (u @ vt), target_w


def lt(source: np.ndarray, target: np.ndarray, ys: np.ndarray, yt: np.ndarray) -> float:
    # Match the primary controlled experiment's target-to-source cosine LT.
    source_n = source / np.linalg.norm(source, axis=1, keepdims=True)
    target_n = target / np.linalg.norm(target, axis=1, keepdims=True)
    transferred = ys[(target_n @ source_n.T).argmax(axis=1)]
    common = np.intersect1d(np.unique(yt), np.unique(transferred))
    mask = np.isin(yt, common) & np.isin(transferred, common)
    if not mask.any():
        return 0.0
    return float(np.mean(yt[mask] == transferred[mask]))


def one_file(path: Path) -> list[dict]:
    # These NPZ objects were generated by the named experiment script; do not
    # use allow_pickle=True on untrusted NPZ files.
    with np.load(path, allow_pickle=True) as data:
        hs, ht = data["H_s"], data["H_t"]
        depth_s, depth_t = data["depth_s"], data["depth_t"]
        ys, yt = data["labels_s"], data["labels_t"]
        seed, pair = int(data["seed"]), str(data["pair"])
    if hs.ndim != 2 or ht.ndim != 2 or hs.shape[1] != ht.shape[1]:
        raise ValueError(f"Invalid embedding shapes in {path}")
    labels = {k: (depth_groups(depth_s, k), depth_groups(depth_t, k)) for k in K_VALUES}
    rng = np.random.RandomState(seed * 1000)
    per_k = {k: [] for k in K_VALUES}
    for _ in range(10):
        q, _ = np.linalg.qr(rng.randn(hs.shape[1], hs.shape[1]))
        rotated = hs @ q
        for k in K_VALUES:
            aligned, processed_target = lga_auto(rotated, ht, *labels[k])
            per_k[k].append(lt(aligned, processed_target, ys, yt))
    base = float(np.mean(per_k[7]))
    return [
        {"pair": pair, "seed": seed, "K": k, "LT": float(np.mean(per_k[k])),
         "delta_LT_vs_K7": float(np.mean(per_k[k]) - base)}
        for k in K_VALUES
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("latent_dir", type=Path, help="Directory with nine donor1_*_seed*.npz files")
    parser.add_argument("output_json", type=Path)
    args = parser.parse_args()
    files = sorted(args.latent_dir.glob("donor1_*_seed*.npz"))
    if len(files) != 9:
        raise ValueError(f"Expected 9 latent files; found {len(files)} in {args.latent_dir}")
    records = [record for path in files for record in one_file(path)]
    summary = []
    for k in K_VALUES:
        subset = [row for row in records if row["K"] == k]
        summary.append({"K": k, "n_pair_seed": len(subset),
                        "mean_LT": float(np.mean([row["LT"] for row in subset])),
                        "mean_delta_LT_vs_K7": float(np.mean([row["delta_LT_vs_K7"] for row in subset])),
                        "sd_delta_LT_vs_K7": float(np.std([row["delta_LT_vs_K7"] for row in subset], ddof=1))})
    result = {"description": "Donor 1 LGA-Auto anatomical-label LT by group count, with each pair-seed value relative to its K=7 value",
              "input_count": len(files), "rotations_per_pair_seed": 10,
              "records": records, "summary": summary}
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    for row in summary:
        print(f"K={row['K']:2d} LT={row['mean_LT']:.6f} ΔLT={row['mean_delta_LT_vs_K7']:+.6f}")


if __name__ == "__main__":
    main()
